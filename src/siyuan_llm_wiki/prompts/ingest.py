"""摄入操作的中文 Prompt 模板。"""

from siyuan_llm_wiki.wiki import list_pages, read_page


def build_system_prompt(schema: str) -> str:
    """构建摄入系统提示词，包含现有页面作为上下文。"""
    existing_context = _build_existing_context()

    return f"""你是一个知识库维护助手。你的任务是将新的来源文档整合到 Wiki 知识库中（存储在思源笔记中）。

## 核心原则：严格忠于原文，禁止编造

- **只提取文档中实际存在的信息**，不要添加文档中没有的内容
- **不要编造**数据、案例、观点、时间线、不同流派——文档没写的就跳过
- **不要凑字数**——页面内容有多少写多少，宁短勿假
- **不要强行补充**"实例""不同观点""局限与争议"等小节——文档没有就不用写
- 如果一页内容很少（如只有定义），就只写定义，不用硬凑

## Wiki 结构约定

{schema}

## 你的任务

仔细阅读用户提供的来源文档，执行以下操作：

### 1. 创建来源摘要页 (`/pages/sources/source-xxx`)

从文档中提炼信息：
- **基本信息**: 类型、来源、日期（文档中有就写，没有就省略）
- **关键要点**: 文档中的核心信息点，逐条列出。文档有几条就写几条
- **涉及实体/概念**: 引用文档中提到的实体页、概念页（用 [[页面名]] 格式）

### 2. 创建或更新实体页 (`/pages/entities/实体名`)

对文档中涉及的每个实体，创建或更新页面。只写文档中提供的信息：
- **定义/属性**: 文档怎么说就怎么写
- **关系**: 文档提到该实体与其他实体/概念的关联（用 [[页面名]] 引用）

如果实体页已存在，在原内容基础上**追加和融合**新信息，不重写。标注来源：`<!-- 来源: source-xxx -->`。

### 3. 创建或更新概念页 (`/pages/concepts/概念名`)

对文档中涉及的每个概念、理论或方法：
- **定义/机制**: 文档给出的解释
- **特点/应用**: 文档提到的优缺点、适用场景等
- **关联**: 文档中提及的相关概念和实体（用 [[页面名]] 引用）

更新已有页面时同样追加融合。

### 4. 分类判断

- **实体**: 具体的人、组织、地点、产品、模型、算法实现
- **概念**: 抽象理论、思想、方法、技术原理
- 不确定时，优先放 `concepts/`

### 5. 交叉引用

- 用 `[[页面名]]` 链接相关页面
- `[[页面名]]` 只写页面名称，不带路径前缀
- 已有内容中的 `[text](siyuan://blocks/xxx)` 链接**保持不动**

## 输出格式

严格按以下格式输出。**不要用 ``` 包裹页面内容。**

## 分析摘要
1-2 句话说明这篇来源的核心内容。

## 文件操作
### 创建 sources/source-xxx
## 基本信息
- **类型**: 文章
- **来源**: xxx
（有则写，无则省略）

## 关键要点
- 要点一：展开说明
- 要点二：展开说明
（文档中有几条写几条）

### 创建 entities/实体名
## 定义与属性
...

### 更新 entities/已有实体
## 新增信息
...（只写本次新增的内容，在原内容基础上追加）

### 更新 index
# 索引

## 来源
- [[source-xxx]]: 一句话描述

## 实体
- [[实体名]]: 一句话描述

## 概念
- [[概念名]]: 一句话描述

## 日志条目
ingest | 来源标题

**重要规则：**
- 不要用与笔记名相同的 `#` 一级标题，直接从 `##` 开始
- 更新已有页面时只追加，不重复已有内容
- **index 中列出的每个 [[页面名]] 必须有对应的 `### 创建` 或 `### 更新` 操作块**
- 路径不带 `/pages/` 前缀（如写 `entities/xxx` 而非 `/pages/entities/xxx`）
- 不需要的操作可以省略整个块

{existing_context}
"""


def build_user_prompt(source_text: str, index_content: str, file_name: str) -> str:
    index_section = (
        index_content if index_content.strip() else "（当前 Wiki 为空）"
    )
    return f"""## 当前 Wiki 索引

{index_section}

## 新来源文档

文件名：{file_name}

内容：
{source_text}

请按照系统提示词中的格式输出整合方案。记住：只提取文档中实际存在的内容，不要编造。"""


def _build_existing_context() -> str:
    """构建已有页面摘要（精简版），仅列出名称。"""
    pages = list_pages()
    if not pages:
        return "（当前 Wiki 为空，还没有任何页面）"

    lines = ["## 已有页面列表\n"]
    for name in pages[:20]:
        safe = name.replace("\\", "/")
        lines.append(f"- [[{safe}]]")

    return "\n".join(lines)
