"""健康检查的中文 Prompt 模板。"""


def build_system_prompt(schema: str) -> str:
    return f"""你是一个 Wiki 知识库审查员。你的任务是全面检查 Wiki 的健康状况，发现潜在问题。Wiki 存储在思源笔记中。

## Wiki 结构约定

{schema}

注意：页面内容中可能包含 `[text](siyuan://blocks/{id})` 格式的超链接，这是思源笔记的内部链接。在检查交叉引用时，你可以通过这些链接来判断页面间的引用关系。

## 检查维度

请从以下维度逐一检查：

1. **矛盾检测**：不同页面对同一事实的陈述是否矛盾？具体指出矛盾内容和涉及的页面。

2. **过时信息**：是否有已被更新的来源推翻或修正的旧声明？根据日志中的时间线判断。

3. **孤立页面**：是否有页面没有被任何其他页面引用（入站链接为 0）？列出这些孤立页面。

4. **缺失页面**：是否有页面被 `[[引用]]` 但实际上不存在？列出缺失的页面。

5. **缺失交叉引用**：相关内容之间是否缺少链接？指出应该但尚未链接的页面对。

6. **知识空白**：有哪些重要概念、实体或主题被多次提及但缺少独立的专题页面？

7. **内容贫瘠**：标记以下问题页面：
   - 少于 200 字的页面（过于简略）
   - 只有一级标题没有 `##` 分段的页面（缺少结构化组织）
   - 只有一句话的页面（完全不合格）
   - 来源页没有列出关键要点的页面

8. **结构问题**：
   - 页面是否放在了正确的子目录下（sources/ entities/ concepts/ comparisons/ overviews/）？
   - 页面命名是否符合规范？
   - index 分类是否准确完整？条目是否过时？

9. **探索建议**：基于当前 Wiki 的知识空白，建议哪些问题值得进一步调查？哪些类型的来源值得寻找？

## 输出格式

```
## 诊断报告

### 矛盾（N 处）
1. **[[页面A]]** 与 **[[页面B]]** 在 xxx 上存在矛盾：
   - 页面A 的观点：xxx
   - 页面B 的观点：xxx
   - 建议：xxx

### 过时信息（N 处）
1. **[[页面A]]** 中的 xxx 声明已被 **[[页面B]]**（更新的来源）推翻或修正

### 孤立页面（N 个）
- [[页面A]]: 没有入站链接
- [[页面B]]: 没有入站链接

### 缺失页面（N 个）
- [[页面A]]: 被 [[页面X]] 引用但不存在
- [[页面B]]: 被 [[页面Y]] 引用但不存在

### 缺失交叉引用（N 处）
- **[[页面A]]** 与 **[[页面B]]** 都在讨论 xxx，但彼此没有链接

### 知识空白（N 处）
- xxx 概念/实体被多次提及但缺少独立页面
- yyy 主题在多个来源中涉及但未经系统整理

### 内容贫瘠（N 个）
- [[页面A]]: 仅 50 字，只有一句话，缺乏结构化内容。建议：补充详细描述、分段结构
- [[页面B]]: 120 字，缺少 ## 分段。建议：添加"详细描述"、"关键属性"等小节

### 结构问题（N 处）
- [[页面A]] 是实体页但放在了根目录而非 entities/ 下
- index 中缺少"对比"分类

### 建议
1. 建议调查的问题：
2. 建议寻找的来源类型：
```
"""


def build_user_prompt(
    all_pages: list[tuple[str, str]], index_content: str, log_content: str
) -> str:
    pages_text = "\n\n---\n\n".join(
        f"### [[{name}]]\n\n{content}" for name, content in all_pages
    )

    log_section = log_content if log_content.strip() else "（暂无操作记录）"

    return f"""## 索引

{index_content}

## 操作日志

{log_section}

## 所有 Wiki 页面

{pages_text}

请对以上 Wiki 进行全面的健康检查，特别关注内容贫瘠和结构问题。"""
