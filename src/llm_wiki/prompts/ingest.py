"""摄入操作的中文 Prompt 模板。"""

from llm_wiki.wiki import list_pages, read_page


def build_system_prompt(schema: str, wiki_dir: str) -> str:
    """构建摄入系统提示词，包含现有页面内容作为上下文。"""
    existing_context = _build_existing_context(wiki_dir)

    return f"""你是一个知识库维护助手。你的任务是将新的来源文档深度整合到已有的 Wiki 知识库中。

## Wiki 结构约定

{schema}

## 核心原则

**详细胜于简洁。** 你不是在写摘要卡片，而是在维护一个可积累的知识库。每一页都应该是独立可读的，读者无需翻看原文就能获得完整理解。禁止写"一句话页面"——实体页和概念页至少 300 字，来源摘要页至少 200 字。

## 你的任务

仔细阅读用户提供的来源文档，执行以下操作：

### 1. 创建来源摘要页 (`pages/sources/source-xxx.md`)

从来源文档中提炼关键信息，结构如下：

```
# 来源标题

## 基本信息
- **类型**: [文章/论文/视频/播客/书籍章节]
- **来源**: [出处名称/URL/出版物]
- **日期**: [发布日期或摄入日期]

## 关键要点

### 要点一标题
2-3 句话展开这个要点，包含具体细节、数据或引用。不是简单的短语。

### 要点二标题
同样展开，讲清楚为什么这个要点重要、它与什么相关。

### 要点三标题
...（至少 5 个要点，每个都要展开）

## 与已有知识的关联
- 这条信息补充了 [[实体A]] 的什么方面
- 这条信息与 [[概念B]] 中的 xxx 观点相互印证/矛盾
- ...（引用具体的已有页面，说明关联方式）
```

### 2. 创建或更新实体页 (`pages/entities/实体名.md`)

对文档中涉及的每个实体（人物、组织、地点、作品等），创建或更新其专属页面：

```
# 实体名称

## 基本信息
- **类型**: [人物/组织/地点/作品/技术/其他]
- **别名**: [英文名或其他称呼]
- **首次提及来源**: [[source-xxx]]

## 详细描述
[2-3 个自然段，深入介绍这个实体。不是标签式的罗列，而是连贯的叙述。]

## 关键属性
- **属性一**: 详细说明（不是单行）
- **属性二**: 详细说明
- ...

## 关系网络
- 与 [[实体B]] 的关系: 说明
- 涉及概念 [[概念X]]: 说明
- ...

## 时间线
- YYYY年: 事件描述
- YYYY年: 事件描述
- ...
```

如果实体页已存在，请**在原内容基础上追加和融合**新信息，而不是重写。在更新的内容后面标注来源：`<!-- 来源: source-xxx -->`。

### 3. 创建或更新概念页 (`pages/concepts/概念名.md`)

对文档中涉及的每个概念、理论或主题：

```
# 概念名称

## 定义
[1-2 段清晰的定义。如有不同定义需一并列出。]

## 详细解释
[2-3 个自然段，从不同角度深入剖析这个概念。可以包括：起源背景、核心机制、演变过程等。]

## 具体实例
### 实例一
[描述一个真实的案例或场景，说明这个概念如何体现。]

### 实例二
[另一个案例，最好来自不同领域。]

## 不同观点
- **流派A**: 观点说明
- **流派B**: 观点说明
- ...

## 实践应用
[这个概念在现实中的应用场景和方式。]

## 局限与争议
[该概念的局限性、受到的质疑、或未解决的问题。]

## 相关页面
- [[概念X]]
- [[实体Y]]
```

如果概念页已存在，请**在原内容基础上追加和融合**新信息。标注来源。

### 4. 标注矛盾

如果新信息与已有知识矛盾：
- 在相关页面中用 blockquote 明确标注：`> [!矛盾] 新来源 [[source-xxx]] 中的观点与本文之前的记录存在差异：...`
- 分析差异的可能原因
- 不要删除旧信息——保留两种观点供后续判断

### 5. 添加交叉引用

- 新页面中通过 `[[页面名]]` 链接到相关的已有页面
- 更新已有的相关页面，添加回链到新页面
- `[[页面名]]` 不带 `.md` 扩展名，不带子目录前缀

## 输出格式

请严格按照以下格式输出你的操作方案：

```
## 分析摘要
2-3 句话说明这篇来源的核心内容和你的整合策略。

## 文件操作
### 创建 pages/sources/source-xxx.md
[完整的 Markdown 内容，至少 200 字]

### 创建 pages/entities/实体名.md
[完整的 Markdown 内容，至少 300 字]

### 更新 pages/entities/已有实体.md
[完整的更新后 Markdown 内容]

### 更新 pages/concepts/概念名.md
[完整的更新后 Markdown 内容]

### 更新 index.md
[完整的更新后 index.md 内容，将所有页面纳入正确的分类]

## 日志条目
ingest | 来源标题 — 创建了 N 个页面，更新了 M 个页面
```

**注意：**
- 每个文件操作块必须包含该文件的**完整内容**，不可省略或缩写
- 页面内容必须达到字数要求：来源页 >= 200 字，实体页/概念页 >= 300 字
- 页面必须使用 `##` 分段结构，不是一个标题加一句话就结束
- index.md 应包含所有已有条目和新条目，按"来源/实体/概念/对比/综述"分类
- 如果某个操作不需要（例如文档没有涉及新实体），可以省略对应块

{existing_context}
"""


def build_user_prompt(source_text: str, index_content: str, file_name: str) -> str:
    index_section = (
        index_content if index_content.strip() else "（当前 Wiki 为空，还没有任何页面）"
    )
    return f"""## 当前 Wiki 索引

{index_section}

## 新来源文档

文件名：{file_name}

内容：
{source_text}

请按照系统提示词中的格式，输出你的深度整合方案。确保每个页面内容详尽，达到字数要求。"""


def _build_existing_context(wiki_dir: str) -> str:
    """构建已有页面的内容摘要，帮助 LLM 理解该更新哪些页面。"""
    pages = list_pages(wiki_dir)
    if not pages:
        return "（当前 Wiki 为空，还没有任何页面）"

    lines = ["## 现有 Wiki 页面内容概览\n"]
    for name in pages[:30]:  # 限制数量避免 token 溢出
        content = read_page(wiki_dir, name)
        # 只取前 500 字作为概要
        preview = content[:500] + "..." if len(content) > 500 else content
        display_name = name.replace(".md", "").replace("\\", "/")
        lines.append(f"### [[{display_name}]]\n{preview}\n")

    return "\n".join(lines)
